// Write generated commands into a plugin folder, and build the local plugin copy that `resync sync` updates.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadLibraryFromDir } from '@resync/shared/node/library';
import { generateCommands } from './generate.js';
import { resyncHome } from '../config.js';

const MARK = 'Generated by `resync plugin build`';

/** The plugin source folder shipped in this repo (packages/plugin). */
export function pluginSourceDir() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../plugin');
}

/** Seed prompt library shipped in this repo (prompts/). */
export function seedPromptsDir() {
  return path.resolve(pluginSourceDir(), '../../prompts');
}

/**
 * Write command files; delete generated files that are no longer produced (hand-written ones are kept).
 * @param {string} commandsDir
 * @param {import('@resync/shared/prompts').Prompt[]} prompts
 */
export async function writeCommands(commandsDir, prompts) {
  const files = generateCommands(prompts);
  await fs.mkdir(commandsDir, { recursive: true });
  const removed = [];
  for (const f of await fs.readdir(commandsDir)) {
    if (!f.endsWith('.md') || f in files) continue;
    const text = await fs.readFile(path.join(commandsDir, f), 'utf8');
    if (text.includes(MARK)) {
      await fs.unlink(path.join(commandsDir, f));
      removed.push(f);
    }
  }
  for (const [name, content] of Object.entries(files)) await fs.writeFile(path.join(commandsDir, name), content, 'utf8');
  return { written: Object.keys(files), removed };
}

/**
 * Merge prompt libraries; later sources win on the same category/slug (synced team library over seeds).
 * @param {string[]} dirs
 */
export async function loadMergedLibrary(dirs) {
  const map = new Map();
  const errors = [];
  for (const d of dirs) {
    const r = await loadLibraryFromDir(d);
    errors.push(...r.errors);
    for (const p of r.prompts) map.set(`${p.category}/${p.slug}`, p);
  }
  return { prompts: [...map.values()], errors };
}

/** Where the local plugin copy lives. */
export function localMarketplaceDir() {
  return path.join(resyncHome(), 'claude-plugin');
}

/**
 * Build ~/.resync/claude-plugin: a local marketplace holding a copy of the plugin with commands generated
 * from the seed prompts plus the synced library (~/.resync/library). Claude Code picks up edits to a
 * local-path marketplace at the next session or on /reload-plugins (docs/VERIFIED.md).
 */
export async function buildLocalPlugin() {
  const root = localMarketplaceDir();
  const pluginDir = path.join(root, 'resync');
  const src = pluginSourceDir();
  await fs.mkdir(root, { recursive: true });
  // Copy the static plugin parts (manifest, hooks, scripts). Commands are regenerated below.
  for (const part of ['.claude-plugin', 'hooks', 'scripts']) {
    await fs.rm(path.join(pluginDir, part), { recursive: true, force: true });
    await fs.cp(path.join(src, part), path.join(pluginDir, part), { recursive: true });
  }
  await fs.mkdir(path.join(root, '.claude-plugin'), { recursive: true });
  await fs.writeFile(
    path.join(root, '.claude-plugin', 'marketplace.json'),
    JSON.stringify({
      name: 'resync-local',
      description: 'ReSync plugin with your synced prompt library (built by `resync plugin build` / `resync sync`)',
      owner: { name: 'ReSync (local build)' },
      plugins: [{ name: 'resync', source: './resync', description: 'ReSync for Claude Code' }],
    }, null, 2) + '\n',
  );
  const { prompts, errors } = await loadMergedLibrary([seedPromptsDir(), path.join(resyncHome(), 'library')]);
  const r = await writeCommands(path.join(pluginDir, 'commands'), prompts);
  return { root, pluginDir, commands: r.written.length, removed: r.removed, errors };
}
